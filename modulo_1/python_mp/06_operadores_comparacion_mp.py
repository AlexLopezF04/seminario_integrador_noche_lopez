print("Operadores de comparación - Cursos Online")

calificacion_1 = float(input("Ingrese la calificación del estudiante 1: "))
calificacion_2 = float(input("Ingrese la calificación del estudiante 2: "))

print(calificacion_1, "==", calificacion_2, calificacion_1 == calificacion_2)

print(calificacion_1, "!=", calificacion_2, calificacion_1 != calificacion_2)

print(calificacion_1, ">", calificacion_2, calificacion_1 > calificacion_2)

print(calificacion_1, "<", calificacion_2, calificacion_1 < calificacion_2)

print(calificacion_1, ">=", calificacion_2, calificacion_1 >= calificacion_2)

print(calificacion_1, "<=", calificacion_2, calificacion_1 <= calificacion_2)
